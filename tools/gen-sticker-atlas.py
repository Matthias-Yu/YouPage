"""Pack the local sticker images and month illustrations. Requires Pillow."""

from pathlib import Path

from PIL import Image, ImageOps


ROOT = Path(__file__).resolve().parents[1] / 'miniprogram'
ASSETS = ROOT / 'assets'
CELL = 128
WIDTH, HEIGHT = 2048, 1024


def main():
    stickers = [(p.stem, p) for p in sorted((ASSETS / 'stickers').glob('*.png'))]
    months = [('month-' + p.stem, p) for p in sorted(Path(__file__).with_name('month-art').glob('*.jpg'))]
    entries = stickers + months
    columns = WIDTH // CELL
    if not entries or len(entries) > columns * (HEIGHT // CELL):
        raise ValueError(f'{len(entries)} images cannot be packed into the atlas')

    atlas = Image.new('RGBA', (WIDTH, HEIGHT))
    index = []
    for i, (key, path) in enumerate(entries):
        with Image.open(path) as source:
            tile = ImageOps.contain(source.convert('RGBA'), (CELL - 8, CELL - 8), Image.Resampling.LANCZOS)
        row, col = divmod(i, columns)
        atlas.paste(tile, (col * CELL + (CELL - tile.width) // 2,
                           row * CELL + (CELL - tile.height) // 2))
        index.append(f"    '{key}': [{col}, {row}]")

    atlas.quantize(colors=256, method=Image.Quantize.FASTOCTREE).save(ASSETS / 'atlas.png', optimize=True)
    (ROOT / 'scene' / 'atlas.js').write_text(
        '// Generated by tools/gen-sticker-atlas.py\n'
        f'module.exports = {{\n  width: {WIDTH},\n  height: {HEIGHT},\n  cell: {CELL},\n  map: {{\n'
        + ',\n'.join(index) + '\n  }\n}\n',
        encoding='utf-8',
    )


if __name__ == '__main__':
    main()
