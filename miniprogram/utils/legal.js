// 运营者和邮箱还没填时，页面上会显示「待填写」
function ready() {
  return !!(config.OPERATOR && config.CONTACT_EMAIL)
}

// 纯文本（导出给公众平台「补充文档」用）
function toText(doc) {
  const out = [doc.title, ''].concat(doc.intro, [''])
  doc.sections.forEach(s => {
    out.push(s.h)
    s.p.forEach(p => out.push(p))
    out.push('')
  })
  return out.concat(doc.outro).join('\n') + '\n'
}

